"""Write js/icon-registry.js from tools/icons/icons.txt (one line per icon: emoji|slug|what the art shows).

The art is assets/icons/<slug>.webp (128 px, transparent), cut from 4x4 GenerateImage sheets by tools/icons/crop_sheets.py.
To add an icon: add a line to icons.txt, paint/crop assets/icons/<slug>.webp, run  python3 tools/build_icons.py
js/icons.js turns every registered emoji the game renders into <img class="wr-icon">, so code and data can keep
using the emoji as the icon's name (WR.icon("⭐") or WR.icon("star")).
"""
import os
ROOT = os.path.join(os.path.dirname(__file__), "..")
os.chdir(ROOT)
rows = [l.split("|") for l in open("tools/icons/icons.txt", encoding="utf8").read().splitlines() if l.strip()]
missing = [s for _, s, _ in rows if not os.path.exists(f"assets/icons/{s}.webp")]
assert not missing, f"missing art: {missing}"
assert len({s for _, s, _ in rows}) == len(rows), "duplicate slug"
body = "|".join(f"{e.replace(chr(0xFE0F), '')} {s}" for e, s, _ in rows)
open("js/icon-registry.js", "w", encoding="utf8").write(
    "/* Generated by tools/build_icons.py from tools/icons/icons.txt — do not edit by hand. emoji slug|emoji slug|… */\n"
    f'window.WR_ICON_LIST = "{body}";\n')
print(f"{len(rows)} icons -> js/icon-registry.js")
