"""T17: write sw.js (offline after one visit) with a content-hash version, so every deploy gets a fresh cache name and the old
cache is deleted (cache-busting). Run after changing any file the app loads:  python3 tools/build_sw.py
Strategy (R17): the app shell + lesson data are precached on install (the data is skipped on Save-Data/cellular); art and
icons are cached when first shown, in an art cache that survives deploys; "Download for offline play" fetches all the art. Pages, JS, CSS and JSON are
network-first (players always get the newest version when online; the cache is the offline fallback). Images are cache-first."""
import hashlib, os, re
ROOT = os.path.join(os.path.dirname(__file__), "..")
os.chdir(ROOT)
html = open("index.html").read()
# R17: install precaches only the app shell (+ the lesson data unless the phone is on Save-Data / cellular); art and icons are
# cached the first time they are shown (plus whatever the first screen showed, sent by js/offline.js), and
# ⚙️ "📲 Download for offline play" fetches the rest (FULL) on request.
shell = ["./", "index.html", "manifest.webmanifest", "assets/manifest.json"]
shell += re.findall(r'(?:src|href)="((?:js|css)/[^"]+)"', html)
shell += ["assets/ui/icon-192.png", "assets/ui/icon-512.png"]
data = []
for dp, _, fs in os.walk("data"):
    data += [os.path.join(dp, f) for f in sorted(fs) if f.endswith(".json")]
data.sort()
art = ["assets/web/" + f for f in sorted(os.listdir("assets/web")) if f.endswith(".webp") and not f.endswith("_1280.webp")]
art += ["assets/icons/" + f for f in sorted(os.listdir("assets/icons")) if f.endswith(".webp")]   # painted UI icons (js/icons.js)
art += ["assets/acc/" + f for f in sorted(os.listdir("assets/acc")) if f.endswith(".webp")]       # accessory layers (js/core.js WR.layerSVG)
shell, data, art = (list(dict.fromkeys(x)) for x in (shell, data, art))
def digest(fl):
    h = hashlib.sha256()
    for f in fl:
        if f != "./": h.update(f.encode()); h.update(open(f, "rb").read())
    return h
h = digest(shell + data); h.update(open("tools/build_sw.py", "rb").read())
ver = h.hexdigest()[:12]
artver = digest(art).hexdigest()[:10]      # the art cache survives deploys that don't change any art
files = shell + data + art
sw = f"""/* Word Realms service worker (generated by tools/build_sw.py — do not edit by hand). Version {ver} */
const VERSION = "wr-{ver}";
const ART = "wrart-{artver}";                                                   // art + icons: cached when first shown, kept across deploys
const VOICE = "wrvoice-1";                                                     // runtime cache for assets/voice (file names change when a line changes)
const SHELL = {shell!r};
const DATA = {data!r};
const ARTFILES = {art!r};
// 📶 R17: on Save-Data or a cellular connection the install skips the lesson data (it is cached as it is used instead)
const lite = () => {{ const c = self.navigator && self.navigator.connection; return !!(c && (c.saveData || c.type === "cellular" || /(^|-)2g$/.test(c.effectiveType || ""))); }};
const put = (cache, list) => caches.open(cache).then(c => Promise.all(list.map(u => c.match(u).then(hit => hit || c.add(new Request(u, {{ cache: "no-cache" }})).catch(() => null)))));
self.addEventListener("install", e => {{
  e.waitUntil(put(VERSION, lite() ? SHELL : SHELL.concat(DATA)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => (k.startsWith("wr-") && k !== VERSION) || (k.startsWith("wrart-") && k !== ART)).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
// js/offline.js: "warm" = keep the art the first screen already showed (it came before this worker was in charge);
// "download" = everything, for ⚙️ 📲 Download for offline play (reports progress back to the page)
self.addEventListener("message", e => {{
  const m = e.data || {{}}, src = e.source;
  if (m.type === "warm") e.waitUntil(put(ART, (m.urls || []).filter(u => ARTFILES.includes(u))));
  if (m.type === "download") {{
    const all = ARTFILES.slice(); let done = 0; const tell = x => src && src.postMessage(Object.assign({{ type: "offline" }}, x));
    e.waitUntil(put(VERSION, SHELL.concat(DATA)).then(() => caches.open(ART)).then(c => Promise.all(all.map(u => c.match(u).then(hit => hit || c.add(new Request(u, {{ cache: "no-cache" }})).catch(() => null)).then(() => {{ if (++done % 40 === 0) tell({{ done, total: all.length }}); }}))))
      .then(() => tell({{ done: all.length, total: all.length, ready: true }})));
  }}
  if (m.type === "status") e.waitUntil(caches.open(ART).then(c => c.keys()).then(ks => src && src.postMessage({{ type: "offline", have: ks.length, total: ARTFILES.length, ready: ks.length >= ARTFILES.length }})));
}});
self.addEventListener("fetch", e => {{
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;            // Supabase, fonts, CDNs: straight to the network
  if (/\\/assets\\/voice\\/[^/]+\\.mp3$/.test(url.pathname)) {{                     // 🎙️ recorded voice lines: not precached; each is kept
    e.respondWith(caches.open(VOICE).then(c => c.match(url.href).then(r => r || fetch(url.href).then(res => {{   // the first time it plays
      if (res.status === 200) c.put(url.href, res.clone()); return res; }}))));                                  // (whole file, so seeking works)
    return;
  }}
  const isImg = /\\.(webp|png|jpe?g|svg|gif)$/i.test(url.pathname);
  if (isImg) {{                                                                    // art: cache first, then network (and keep it)
    e.respondWith(caches.match(req).then(r => r || fetch(req).then(res => {{ if (res.ok) {{ const cp = res.clone(); caches.open(ART).then(c => c.put(req, cp)); }} return res; }})));
    return;
  }}
  e.respondWith(fetch(req).then(res => {{                                          // pages, code, data: network first
    if (res.ok) {{ const cp = res.clone(); caches.open(VERSION).then(c => c.put(req, cp)); }}
    return res;
  }}).catch(() => caches.match(req, {{ ignoreSearch: true }}).then(r => r || (req.mode === "navigate" ? caches.match("index.html") : Response.error()))));
}});
"""
open("sw.js", "w").write(sw)
print("sw.js", ver, "shell+data", len(shell) + len(data), "art", len(art), artver)
