"""T17 / first-visit: write sw.js with a content-hash version, so every deploy gets a fresh shell cache and the old
shell cache is deleted. Run after changing any file the app loads:  python3 tools/build_sw.py

Strategy: install stores the app shell and the small home JSON only. Lesson banks and voice lookup files are saved in
wrdata the first time they are fetched (and kept across deploys). Pictures are saved when first shown, in an art cache
that also survives deploys. Settings → Download fetches every bank, both voice lookups, and every picture.
Pages, JS, CSS and JSON are network-first when online. Images are cache-first. Supabase is never cached."""
import hashlib, os, re
ROOT = os.path.join(os.path.dirname(__file__), "..")
os.chdir(ROOT)
html = open("index.html").read()
# Install: the app shell, plus the few JSON files the map needs so a reload with no network still opens.
# Lesson banks are not in this list (they were, and the first visit sat against a 2 MB ceiling).
shell = ["./", "index.html", "manifest.webmanifest", "assets/manifest.json"]
shell += re.findall(r'data-shell="((?:js|css)/[^"]+)"', html)
shell += ["assets/ui/icon-192.png"]   # the 512 install icon waits in the art cache until the phone installs
core = [f for f in [
    "data/realms.json", "data/shop.json", "data/anchors.json", "data/counts.json", "data/lessons/index.json",
] if os.path.exists(f)]
data = []
for dp, _, fs in os.walk("data"):
    data += [os.path.join(dp, f) for f in sorted(fs) if f.endswith(".json")]
data.sort()
voice_meta = [f for f in ["assets/voice/manifest.json", "assets/voice/manifest-story.json"] if os.path.exists(f)]
art = ["assets/web/" + f for f in sorted(os.listdir("assets/web")) if f.endswith(".webp") and not f.endswith("_1280.webp")]
art += ["assets/icons/" + f for f in sorted(os.listdir("assets/icons")) if f.endswith(".webp")]   # painted UI icons (js/icons.js)
art += ["assets/ui/icon-512.png"]
art += ["assets/acc/" + f for f in sorted(os.listdir("assets/acc")) if f.endswith(".webp")]       # accessory layers (js/core.js WR.layerSVG)
shell, core, data, voice_meta, art = (list(dict.fromkeys(x)) for x in (shell, core, data, voice_meta, art))
def digest(fl):
    h = hashlib.sha256()
    for f in fl:
        if f != "./": h.update(f.encode()); h.update(open(f, "rb").read())
    return h
h = digest(shell + core); h.update(open("tools/build_sw.py", "rb").read())
ver = h.hexdigest()[:12]
artver = digest(art).hexdigest()[:10]      # the art cache survives deploys that don't change any art
sw = f"""/* Word Realms service worker (generated by tools/build_sw.py — do not edit by hand). Version {ver} */
const VERSION = "wr-{ver}";
const ART = "wrart-{artver}";                                                   // pictures: cached when first shown, kept across deploys
const BANK = "wrdata";                                                          // lesson banks + voice lookups: kept across deploys
const VOICE = "wrvoice-1";                                                     // runtime cache for assets/voice MP3s (names change when a line changes)
const SHELL = {shell!r};
const CORE = {core!r};                                                          // home JSON, precached so the map opens offline
const DATA = {data!r};                                                          // every bank; fetched on use, or by Settings → Download
const META = {voice_meta!r};                                                   // voice lookups; not on the first map (js/voice.js loads them on the first spoken line)
const ARTFILES = {art!r};
const isBank = (path) => /\\/data\\/.+\\.json$/.test(path) || /\\/assets\\/voice\\/manifest[^/]*\\.json$/.test(path);
// fresh=true revalidates (Download). Install and the art warm-up use the normal cache so files the page just loaded are not fetched twice.
const put = (cache, list, fresh) => caches.open(cache).then(c => Promise.all(list.map(u => c.match(u).then(hit => hit || c.add(new Request(u, fresh ? {{ cache: "no-cache" }} : {{}})).catch(() => null)))));
// Copy banks and voice lookups out of the previous shell cache before that cache is deleted, so a full offline
// download from the old app is still here after an update.
const keepData = async () => {{
  const names = await caches.keys(), old = names.filter(k => k.startsWith("wr-") && k !== VERSION);
  if (!old.length) return 0;
  const dest = await caches.open(BANK); let n = 0;
  for (const k of old) {{
    const c = await caches.open(k);
    for (const req of await c.keys()) {{
      if (!isBank(new URL(req.url).pathname) || await dest.match(req)) continue;
      const res = await c.match(req); if (res) {{ await dest.put(req, res); n++; }}
    }}
  }}
  return n;
}};
self.addEventListener("install", e => {{
  // The page waits until this worker is in charge, then loads the shell once. This handler must not
  // fetch it again: cache.add() does not reuse a response the page already received.
  e.waitUntil(self.skipWaiting());
}});
self.addEventListener("activate", e => {{
  e.waitUntil(keepData().then(() => caches.keys()).then(ks => Promise.all(ks.filter(k => (k.startsWith("wr-") && k !== VERSION) || (k.startsWith("wrart-") && k !== ART)).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
// js/offline.js: "warm" = keep the art the first screen already showed (it came before this worker was in charge);
// "download" = every bank, both voice lookups, and every picture (⚙️ Download);
// "adopt" = the same copy activate runs, so a test can prove an old precache is kept
self.addEventListener("message", e => {{
  const m = e.data || {{}}, src = e.source;
  if (m.type === "warm") e.waitUntil(put(ART, (m.urls || []).filter(u => ARTFILES.includes(u))));
  if (m.type === "adopt") e.waitUntil(keepData().then(n => src && src.postMessage({{ type: "adopted", n }})));
  if (m.type === "download") {{
    const packs = DATA.concat(META), all = ARTFILES.slice(), total = packs.length + all.length; let done = 0;
    const tell = x => src && src.postMessage(Object.assign({{ type: "offline" }}, x));
    const step = () => {{ done++; if (done % 40 === 0 || done === total) tell({{ done, total }}); }};
    e.waitUntil(Promise.all([
      put(VERSION, SHELL, true),
      put(BANK, packs, true).then(() => packs.forEach(step)),
      caches.open(ART).then(c => Promise.all(all.map(u => c.match(u).then(hit => hit || c.add(new Request(u, {{ cache: "no-cache" }})).catch(() => null)).then(step))))
    ]).then(() => tell({{ done: total, total, ready: true }})));
  }}
  if (m.type === "status") e.waitUntil(Promise.all([
    caches.open(ART).then(c => c.keys()),
    caches.open(BANK).then(c => Promise.all(DATA.concat(META).map(u => c.match(u))))
  ]).then(([ks, hits]) => src && src.postMessage({{ type: "offline", have: ks.length, total: ARTFILES.length, ready: ks.length >= ARTFILES.length && hits.every(Boolean) }})));
}});
self.addEventListener("fetch", e => {{
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;            // Supabase, fonts, CDNs: straight to the network
  if (/\\/assets\\/voice\\/[^/]+\\.mp3$/.test(url.pathname)) {{                     // 🎙️ recorded voice lines: not precached; each is kept
    e.respondWith(caches.open(VOICE).then(c => c.match(url.href).then(r => r || fetch(url.href).then(res => {{   // the first time it plays
      if (res.status === 200) c.put(url.href, res.clone()); return res; }}))));                                  // (whole file, so seeking works)
    return;
  }}
  const isImg = /\\.(webp|png|jpe?g|svg|gif)$/i.test(url.pathname);
  if (isImg) {{                                                                    // art: cache first, then network (and keep it before the page uses it)
    e.respondWith(caches.match(req).then(r => r || fetch(req).then(async res => {{ if (res.ok) await caches.open(ART).then(c => c.put(req, res.clone())); return res; }})));
    return;
  }}
  const store = isBank(url.pathname) ? BANK : VERSION;                            // banks survive a new shell; code does not
  e.respondWith((async () => {{                                                    // network first; the copy is stored before the page reads it
    try {{
      const res = await fetch(req);
      if (res.ok) await caches.open(store).then(c => c.put(req, res.clone()));
      return res;
    }} catch (err) {{
      const hit = await caches.match(req, {{ ignoreSearch: true }});
      return hit || (req.mode === "navigate" ? caches.match("index.html") : Response.error());
    }}
  }})());
}});
"""
open("sw.js", "w").write(sw)
print("sw.js", ver, "shell", len(shell), "core", len(core), "banks", len(data), "art", len(art), artver)
