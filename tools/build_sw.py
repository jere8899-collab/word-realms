"""T17: write sw.js (offline after one visit) with a content-hash version, so every deploy gets a fresh cache name and the old
cache is deleted (cache-busting). Run after changing any file the app loads:  python3 tools/build_sw.py
Strategy: the app shell + all lesson data + the light WebP art are precached on install. Pages, JS, CSS and JSON are
network-first (players always get the newest version when online; the cache is the offline fallback). Images are cache-first."""
import hashlib, os, re
ROOT = os.path.join(os.path.dirname(__file__), "..")
os.chdir(ROOT)
html = open("index.html").read()
files = ["./", "index.html", "manifest.webmanifest", "assets/manifest.json"]
files += re.findall(r'(?:src|href)="((?:js|css)/[^"]+)"', html)
for d in ("data",):
    for dp, _, fs in os.walk(d):
        files += [os.path.join(dp, f) for f in sorted(fs) if f.endswith(".json")]
files += ["assets/web/" + f for f in sorted(os.listdir("assets/web")) if f.endswith(".webp") and not f.endswith("_1280.webp")]
files += ["assets/icons/" + f for f in sorted(os.listdir("assets/icons")) if f.endswith(".webp")]   # painted UI icons (js/icons.js)
files += ["assets/ui/icon-192.png", "assets/ui/icon-512.png"]
files = list(dict.fromkeys(files))
h = hashlib.sha256()
for f in files:
    if f != "./": h.update(f.encode()); h.update(open(f, "rb").read())
h.update(open("tools/build_sw.py", "rb").read())
ver = h.hexdigest()[:12]
sw = f"""/* Word Realms service worker (generated by tools/build_sw.py — do not edit by hand). Version {ver} */
const VERSION = "wr-{ver}";
const PRECACHE = {files!r};
self.addEventListener("install", e => {{
  e.waitUntil(caches.open(VERSION).then(c => Promise.all(PRECACHE.map(u => c.add(new Request(u, {{ cache: "reload" }})).catch(() => null)))).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("wr-") && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener("fetch", e => {{
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;            // Supabase, fonts, CDNs: straight to the network
  const isImg = /\\.(webp|png|jpe?g|svg|gif)$/i.test(url.pathname);
  if (isImg) {{                                                                    // art: cache first, then network (and keep it)
    e.respondWith(caches.match(req).then(r => r || fetch(req).then(res => {{ if (res.ok) {{ const cp = res.clone(); caches.open(VERSION).then(c => c.put(req, cp)); }} return res; }})));
    return;
  }}
  e.respondWith(fetch(req).then(res => {{                                          // pages, code, data: network first
    if (res.ok) {{ const cp = res.clone(); caches.open(VERSION).then(c => c.put(req, cp)); }}
    return res;
  }}).catch(() => caches.match(req, {{ ignoreSearch: true }}).then(r => r || (req.mode === "navigate" ? caches.match("index.html") : Response.error()))));
}});
"""
open("sw.js", "w").write(sw)
print("sw.js", ver, len(files), "files")
